#Функция токенизации

def tokenize_advanced(text):

    text = text.lower()


    punctuation = '!"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~0123456789'
    for char in punctuation:
        text = text.replace(char, ' ')


    tokens = text.split()


    stop_words = {
        'и', 'в', 'во', 'не', 'что', 'он', 'на', 'я', 'с', 'со', 'как', 'а',
        'то', 'все', 'она', 'так', 'его', 'но', 'да', 'ты', 'к', 'у', 'же',
        'вы', 'за', 'бы', 'по', 'только', 'ее', 'мне', 'было', 'вот', 'от',
        'меня', 'еще', 'нет', 'о', 'из', 'ему', 'теперь', 'когда', 'даже',
        'ну', 'вдруг', 'ли', 'если', 'уже', 'или', 'ни', 'быть', 'был', 'него',
        'до', 'вас', 'нибудь', 'опять', 'уж', 'вам', 'ведь', 'там', 'потом',
        'себя', 'ничего', 'ей', 'может', 'они', 'тут', 'где', 'есть', 'надо',
        'ней', 'для', 'мы', 'тебя', 'их', 'чем', 'была', 'сам', 'чтоб', 'без',
        'будто', 'чего', 'раз', 'тоже', 'себе', 'под', 'будет', 'ж', 'тогда',
        'кто', 'этот', 'того', 'потому', 'этого', 'какой', 'совсем', 'ним',
        'здесь', 'этом', 'один', 'почти', 'мой', 'тем', 'чтобы', 'нее', 'сейчас',
        'были', 'куда', 'зачем', 'всех', 'никогда', 'можно', 'при', 'наконец',
        'два', 'об', 'другой', 'хоть', 'после', 'над', 'больше', 'тот', 'через',
        'эти', 'нас', 'про', 'всего', 'них', 'какая', 'много', 'разве', 'три',
        'эту', 'моя', 'впрочем', 'хорошо', 'свою', 'этой', 'перед', 'иногда',
        'лучше', 'чуть', 'том', 'нельзя', 'такой', 'им', 'более', 'всегда',
        'конечно', 'всю', 'между'
    }


    tokens = [word for word in tokens if word not in stop_words]

    # Простейшая лемматизация (приводим к базовой форме)
    lemmas = []
    for word in tokens:
        # Убираем частицы "-то", "-ка" и т.д.
        if word.endswith(('то', 'ка', 'либо', 'нибудь')):
            word = word[:-2]
        # Убираем притяжательные окончания ("мамин" → "мама")
        if word.endswith(('ин', 'ын', 'ов', 'ев')):
            word = word[:-2] + 'а'  # упрощенное правило
        lemmas.append(word)

    return lemmas
























